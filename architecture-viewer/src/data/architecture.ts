type NodeDetails = Pick<
  ArchitectureNodeData,
  | "responsibility"
  | "preconditions"
  | "success"
  | "unknown"
  | "failures"
  | "retry"
  | "configKeys"
  | "codeLinks"
  | "tags"
>;

const node = (
  id: string,
  title: string,
  summary: string,
  kind: NodeKind,
  phase: string,
  details: NodeDetails,
): ArchitectureNode => ({
  id,
  type: "architecture",
  position: { x: 0, y: 0 },
  data: {
    ...details,
    title,
    summary,
    kind,
    phase,
    responsibility: details.responsibility,
  },
});

const edge = (
  id: string,
  source: string,
  target: string,
  label?: string,
): ArchitectureEdge => ({
  id,
  source,
  target,
  label,
  type: "smoothstep",
  animated: label === "да" || label === "продолжить",
});

